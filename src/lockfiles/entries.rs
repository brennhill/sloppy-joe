//! Every package a parsed lockfile pins, with the integrity and source it records: what
//! `fix-lockfile` compares between the committed lockfile and a regenerated candidate, read from
//! the same parsed representation the scan uses (docs/specs/fix-lockfile.md, Verification).

use super::*;

/// One locked package: identity plus what must not change when the lockfile is regenerated.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub(crate) struct LockedPackage {
    /// Package name as the ecosystem compares it (PEP 503 normalized for Python).
    pub(crate) name: String,
    pub(crate) version: String,
    /// Recorded integrity (hashes joined in sorted order); `None` when none is recorded.
    pub(crate) integrity: Option<String>,
    /// Recorded source (registry, tarball URL, git reference); `None` when none is recorded.
    pub(crate) source: Option<String>,
}

fn entry(name: &str, version: &str, integrity: Option<String>, source: Option<String>) -> LockedPackage {
    LockedPackage {
        name: name.to_string(),
        version: version.to_string(),
        integrity: integrity.filter(|value| !value.is_empty()),
        source: source.filter(|value| !value.is_empty()),
    }
}

fn json_str(value: &serde_json::Value, key: &str) -> Option<String> {
    value.get(key).and_then(|v| v.as_str()).map(str::to_string)
}

fn joined(mut values: Vec<String>) -> Option<String> {
    values.retain(|value| !value.is_empty());
    values.sort();
    values.dedup();
    (!values.is_empty()).then(|| values.join(","))
}

impl LockfileData {
    /// Every package the lockfile pins. Errors for formats `fix-lockfile` never regenerates, so a
    /// comparison is never made against an empty list by mistake.
    pub(crate) fn locked_packages(&self) -> Result<Vec<LockedPackage>> {
        let mut packages = match &self.parsed {
            ParsedLockfile::Npm { value, .. } => npm_packages(value),
            ParsedLockfile::NpmLegacy { value, .. } => {
                let mut out = Vec::new();
                if let Some(dependencies) = value.get("dependencies").and_then(|v| v.as_object()) {
                    npm_v1_packages(dependencies, &mut out);
                }
                out
            }
            ParsedLockfile::Pnpm { value, .. } => pnpm_packages(value),
            ParsedLockfile::Bun { value, .. } => bun_packages(value),
            ParsedLockfile::Yarn(parsed) => parsed.locked_packages()?,
            ParsedLockfile::Cargo(value) => cargo_packages(value),
            ParsedLockfile::Composer(value) => composer_packages(value),
            ParsedLockfile::Python(value) => poetry_packages(value),
            ParsedLockfile::Uv(value) => uv_packages(value),
            ParsedLockfile::None => Vec::new(),
            ParsedLockfile::Pipfile(_)
            | ParsedLockfile::Gradle(_)
            | ParsedLockfile::Dotnet(_)
            | ParsedLockfile::Ruby(_) => anyhow::bail!(
                "this lockfile format is never regenerated by fix-lockfile, so its entries are not compared"
            ),
        };
        packages.sort();
        packages.dedup();
        Ok(packages)
    }

    /// `(name, version)` of every package the scanned project reaches, or `None` when the format's
    /// reachability is not modeled (every locked package then counts as reachable).
    pub(crate) fn reachable_packages(&self) -> Option<HashSet<(String, String)>> {
        let python = matches!(self.parsed, ParsedLockfile::Python(_) | ParsedLockfile::Uv(_));
        if matches!(
            self.parsed,
            ParsedLockfile::NpmLegacy { .. } | ParsedLockfile::None
        ) {
            return None;
        }
        let name = |name: &str| {
            if python {
                python_hashes::normalize_name(name)
            } else {
                name.to_string()
            }
        };
        let mut reachable: HashSet<(String, String)> = self
            .resolution
            .exact_versions
            .iter()
            .map(|(key, resolved)| (name(&key.package), resolved.version.clone()))
            .collect();
        reachable.extend(self.transitive_deps.iter().filter_map(|dep| {
            Some((name(dep.package_name()), dep.version.clone()?))
        }));
        Some(reachable)
    }
}

fn npm_packages(value: &serde_json::Value) -> Vec<LockedPackage> {
    let Some(packages) = value.get("packages").and_then(|v| v.as_object()) else {
        return Vec::new();
    };
    packages
        .iter()
        .filter(|(key, entry)| {
            key.contains("node_modules/")
                && !entry.get("link").and_then(|v| v.as_bool()).unwrap_or(false)
        })
        .filter_map(|(key, entry)| {
            let installed = key.rsplit_once("node_modules/").map_or(key.as_str(), |(_, n)| n);
            let name = entry.get("name").and_then(|v| v.as_str()).unwrap_or(installed);
            let version = entry.get("version").and_then(|v| v.as_str())?;
            Some(entry_from_json(name, version, entry))
        })
        .collect()
}

fn entry_from_json(name: &str, version: &str, value: &serde_json::Value) -> LockedPackage {
    entry(
        name,
        version,
        json_str(value, "integrity"),
        json_str(value, "resolved"),
    )
}

fn npm_v1_packages(
    dependencies: &serde_json::Map<String, serde_json::Value>,
    out: &mut Vec<LockedPackage>,
) {
    for (key, value) in dependencies {
        if let Some(raw_version) = value.get("version").and_then(|v| v.as_str()) {
            let (name, version) = raw_version
                .strip_prefix("npm:")
                .and_then(|alias| alias.rsplit_once('@').filter(|(n, _)| !n.is_empty()))
                .unwrap_or((key.as_str(), raw_version));
            out.push(entry_from_json(name, version, value));
        }
        if let Some(nested) = value.get("dependencies").and_then(|v| v.as_object()) {
            npm_v1_packages(nested, out);
        }
    }
}

fn yaml_str(value: Option<&serde_yaml::Value>, key: &str) -> Option<String> {
    value
        .and_then(|v| v.get(key))
        .and_then(|v| v.as_str())
        .map(str::to_string)
}

fn pnpm_packages(value: &serde_yaml::Value) -> Vec<LockedPackage> {
    let Some(packages) = value.get("packages").and_then(|v| v.as_mapping()) else {
        return Vec::new();
    };
    packages
        .iter()
        .filter_map(|(key, value)| {
            let (name, version) = pnpm::pnpm_package_key_parts(key.as_str()?)?;
            Some(pnpm_entry(name, version, value))
        })
        .collect()
}

fn pnpm_entry(name: &str, version: &str, value: &serde_yaml::Value) -> LockedPackage {
    let resolution = value.get("resolution");
    let source = ["tarball", "directory", "repo", "commit"]
        .iter()
        .filter_map(|field| yaml_str(resolution, field).map(|v| format!("{field}={v}")))
        .collect();
    entry(
        name,
        version,
        yaml_str(resolution, "integrity"),
        joined(source),
    )
}

/// Packages of a pnpm lockfile in any format version (5.x keys `/name/1.0.0`, 6.x keys
/// `/name@1.0.0`, 9.x keys `name@1.0.0`), for the lockfile a format upgrade replaces. The scan
/// itself only models 9.0, so this reader is used for nothing but the comparison.
pub(crate) fn pnpm_legacy_packages(content: &str) -> Result<Vec<LockedPackage>> {
    let value = parse_yaml_guarded(content)?;
    let Some(packages) = value.get("packages").and_then(|v| v.as_mapping()) else {
        return Ok(Vec::new());
    };
    let mut out = Vec::new();
    for (key, package) in packages {
        let key = key
            .as_str()
            .ok_or_else(|| anyhow::anyhow!("a pnpm-lock.yaml package key is not a string"))?;
        let Some((name, version)) = legacy_pnpm_key(key) else {
            anyhow::bail!(
                "pnpm-lock.yaml package key '{}' is not in a known format",
                crate::report::sanitize_for_terminal(key)
            );
        };
        out.push(pnpm_entry(&name, &version, package));
    }
    out.sort();
    out.dedup();
    Ok(out)
}

fn legacy_pnpm_key(key: &str) -> Option<(String, String)> {
    let key = key.trim().trim_start_matches('/');
    let key = key.split('(').next().unwrap_or(key);
    let scoped = key.starts_with('@');
    let body = if scoped { &key[1..] } else { key };
    let name_end = if scoped { body.find('/')? + 1 } else { 0 };
    let rest = &body[name_end..];
    // 6.x and 9.x: name@version; 5.x: name/version with an optional `_peer` suffix.
    // Whichever separator comes first ends the name: a 5.x peer suffix can contain an `@`.
    let split = rest.find(['@', '/'])?;
    let name = format!("{}{}", if scoped { "@" } else { "" }, &body[..name_end + split]);
    let version = rest[split + 1..].split('_').next().unwrap_or_default();
    (!name.is_empty() && !version.is_empty()).then(|| (name, version.to_string()))
}

fn bun_packages(value: &serde_json::Value) -> Vec<LockedPackage> {
    let Some(packages) = value.get("packages").and_then(|v| v.as_object()) else {
        return Vec::new();
    };
    packages
        .values()
        .filter_map(|value| {
            let parts = value.as_array()?;
            let descriptor = parts.first()?.as_str()?;
            let split = descriptor.get(1..)?.rfind('@')? + 1;
            let (name, version) = (&descriptor[..split], &descriptor[split + 1..]);
            Some(entry(
                name,
                version,
                parts.get(3).and_then(|v| v.as_str()).map(str::to_string),
                parts.get(1).and_then(|v| v.as_str()).map(str::to_string),
            ))
        })
        .collect()
}

fn toml_str(table: &toml::value::Table, key: &str) -> Option<String> {
    table.get(key).and_then(|v| v.as_str()).map(str::to_string)
}

fn toml_packages(value: &toml::Value) -> impl Iterator<Item = &toml::value::Table> {
    value
        .get("package")
        .and_then(|v| v.as_array())
        .into_iter()
        .flatten()
        .filter_map(|v| v.as_table())
}

fn cargo_packages(value: &toml::Value) -> Vec<LockedPackage> {
    let metadata = value.get("metadata").and_then(|v| v.as_table());
    toml_packages(value)
        .filter_map(|package| {
            let name = toml_str(package, "name")?;
            let version = toml_str(package, "version")?;
            let legacy = metadata.and_then(|table| {
                let prefix = format!("checksum {name} {version} (");
                table
                    .iter()
                    .find(|(key, _)| key.starts_with(&prefix))
                    .and_then(|(_, v)| v.as_str().map(str::to_string))
            });
            let checksum = toml_str(package, "checksum").or(legacy);
            Some(entry(&name, &version, checksum, toml_str(package, "source")))
        })
        .collect()
}

fn composer_packages(value: &serde_json::Value) -> Vec<LockedPackage> {
    ["packages", "packages-dev"]
        .iter()
        .filter_map(|section| value.get(*section).and_then(|v| v.as_array()))
        .flatten()
        .filter_map(|package| {
            let name = package.get("name")?.as_str()?;
            let version = package.get("version")?.as_str()?;
            let dist = package.get("dist");
            let source = package.get("source");
            let field = |table: Option<&serde_json::Value>, key: &str| {
                table.and_then(|t| json_str(t, key)).unwrap_or_default()
            };
            Some(entry(
                name,
                version,
                joined(vec![
                    field(dist, "shasum"),
                    field(dist, "reference"),
                    field(source, "reference"),
                ]),
                joined(vec![field(dist, "url"), field(source, "url")]),
            ))
        })
        .collect()
}

fn toml_source(package: &toml::value::Table) -> Option<String> {
    package.get("source").map(|source| source.to_string())
}

fn poetry_packages(value: &toml::Value) -> Vec<LockedPackage> {
    toml_packages(value)
        .filter_map(|package| {
            let name = python_hashes::normalize_name(&toml_str(package, "name")?);
            let version = toml_str(package, "version")?;
            let hashes = package
                .get("files")
                .and_then(|v| v.as_array())
                .into_iter()
                .flatten()
                .filter_map(|file| file.get("hash").and_then(|h| h.as_str()))
                .map(str::to_string)
                .collect();
            Some(entry(&name, &version, joined(hashes), toml_source(package)))
        })
        .collect()
}

fn uv_packages(value: &toml::Value) -> Vec<LockedPackage> {
    toml_packages(value)
        .filter_map(|package| {
            let name = python_hashes::normalize_name(&toml_str(package, "name")?);
            let version = toml_str(package, "version").unwrap_or_default();
            let sdist = package
                .get("sdist")
                .and_then(|s| s.get("hash"))
                .and_then(|h| h.as_str())
                .map(str::to_string);
            let wheels = package
                .get("wheels")
                .and_then(|v| v.as_array())
                .into_iter()
                .flatten()
                .filter_map(|wheel| wheel.get("hash").and_then(|h| h.as_str()))
                .map(str::to_string);
            let hashes = sdist.into_iter().chain(wheels).collect();
            Some(entry(&name, &version, joined(hashes), toml_source(package)))
        })
        .collect()
}

