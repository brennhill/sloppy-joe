//! Regression tests for lockfile red-team findings (parser level).

use super::*;
use std::sync::atomic::{AtomicU64, Ordering};

static COUNTER: AtomicU64 = AtomicU64::new(0);

fn unique_dir() -> PathBuf {
    let id = COUNTER.fetch_add(1, Ordering::SeqCst);
    let dir = std::env::temp_dir().join(format!("sj-lockrt-{}-{}", std::process::id(), id));
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

fn npm_dep(name: &str, version: &str) -> Dependency {
    Dependency {
        name: name.to_string(),
        version: Some(version.to_string()),
        ecosystem: Ecosystem::Npm,
        actual_name: None,
    }
}

#[test]
fn npm_lockfile_version_parsing_is_strict() {
    for ok in [1u64, 2, 3] {
        let value = serde_json::json!({ "lockfileVersion": ok });
        assert_eq!(npm::lockfile_version(&value).unwrap(), ok);
    }
    for bad in [
        serde_json::json!({ "lockfileVersion": 1.0 }),
        serde_json::json!({ "lockfileVersion": "1" }),
        serde_json::json!({ "lockfileVersion": "3" }),
        serde_json::json!({ "lockfileVersion": 4 }),
        serde_json::json!({ "lockfileVersion": 0 }),
        serde_json::json!({ "lockfileVersion": null }),
        serde_json::json!({}),
    ] {
        assert!(
            npm::lockfile_version(&bad).is_err(),
            "{bad} must be rejected"
        );
    }
}

#[test]
fn npm_lockfile_data_rejects_noncanonical_lockfile_version() {
    let dir = unique_dir();
    let lockfile = dir.join("package-lock.json");
    std::fs::write(
        &lockfile,
        r#"{"lockfileVersion": 1.0, "dependencies": {"lodash": {"version": "4.17.21"}}}"#,
    )
    .unwrap();
    let deps = vec![npm_dep("lodash", "^4.17.21")];
    assert!(
        LockfileData::parse_for_kind_with_lockfile(
            &dir,
            Some(crate::ProjectInputKind::Npm),
            &deps,
            Some(&lockfile),
        )
        .is_err(),
        "lockfileVersion 1.0 must not be treated as a modern lockfile"
    );
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn yarn_classic_scoped_selector_with_multibyte_leaf_does_not_panic() {
    let content = r#"# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@evil/ñpkg@^1.0.0":
  version "1.0.0"
  resolved "https://registry.yarnpkg.com/@evil/ñpkg/-/ñpkg-1.0.0.tgz#abc"
  integrity sha512-abc

"@e/ñ@^2.0.0":
  version "2.0.0"
  resolved "https://registry.yarnpkg.com/@e/ñ/-/ñ-2.0.0.tgz#abc"
  integrity sha512-abc
"#;
    let dir = unique_dir();
    let parsed =
        yarn::parse_lockfile(content, dir.join("yarn.lock"), &dir).expect("yarn.lock should parse");
    yarn::validate_provenance(&parsed).expect("registry entries should validate cleanly");
    let names = yarn::parse_all_from_parsed(&parsed)
        .unwrap()
        .into_iter()
        .map(|dep| dep.name)
        .collect::<Vec<_>>();
    assert!(names.contains(&"@evil/ñpkg".to_string()), "{names:?}");
    assert!(names.contains(&"@e/ñ".to_string()), "{names:?}");
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn yarn_entries_with_unparseable_selectors_block_provenance() {
    let content = r#"# yarn lockfile v1


"@scope-without-slash":
  version "1.0.0"
  resolved "https://evil.example/pkg.tgz"
  integrity sha512-abc
"#;
    let dir = unique_dir();
    let parsed =
        yarn::parse_lockfile(content, dir.join("yarn.lock"), &dir).expect("yarn.lock should parse");
    assert!(
        yarn::validate_provenance(&parsed).is_err(),
        "entries whose selectors cannot be attributed must not be skipped"
    );
    let _ = std::fs::remove_dir_all(&dir);
}

fn deep(open: &str, close: &str, depth: usize) -> String {
    format!("{}{}", open.repeat(depth), close.repeat(depth))
}

#[test]
fn json5_depth_guard_blocks_deep_nesting_without_overflowing() {
    let content = format!(
        r#"{{"lockfileVersion": 1, "x": {}}}"#,
        deep("[", "]", 200_000)
    );
    let err = parse_json5_guarded(&content).expect_err("deep nesting must be rejected");
    assert!(err.to_string().contains("nest"), "{err}");

    let mixed = format!(r#"{{"x": {}}}"#, deep(r#"{"a":"#, "}", 5_000));
    assert!(parse_json5_guarded(&mixed).is_err());
}

