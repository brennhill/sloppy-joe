#[test]
fn yarn_workspace_member_neither_scans_nor_flags_root_orphans() {
    let dir = unique_dir();
    std::fs::create_dir_all(dir.join("packages/web")).unwrap();
    let lockfile = dir.join("yarn.lock");
    std::fs::write(&lockfile, format!("{BERRY_LOCK}{BERRY_ORPHANS}")).unwrap();
    std::fs::write(
        dir.join("packages/web/package.json"),
        r#"{"name":"web","dependencies":{"scheduler":"^0.23.2"}}"#,
    )
    .unwrap();
    let deps = crate::parsers::package_json::parse(&dir.join("packages/web")).unwrap();
    let lock = LockfileData::parse_for_kind_with_lockfile(
        &dir.join("packages/web"),
        Some(LockfileKind::Ecosystem(Ecosystem::Npm)),
        &deps,
        Some(&lockfile),
    )
    .unwrap();
    let names = scanned(&lock);
    assert!(!names.contains(&"ghost".to_string()), "{names:?}");
    assert!(
        orphan_issue(&lock).is_none(),
        "{:?}",
        lock.resolution.issues
    );
    let _ = std::fs::remove_dir_all(&dir);
}

