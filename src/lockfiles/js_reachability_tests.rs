//! Yarn lockfile reachability: real dependencies must always be scanned, while
//! entries no dependency reaches (stale orphans, never installed) are flagged
//! with a non-blocking warning instead of being scanned. Whenever reachability
//! is uncertain, orphans are scanned (fail closed). Also covers invalid package
//! names in yarn.lock and pnpm-lock.yaml blocking instead of being dropped.

use super::*;
use crate::report::Severity;
use std::sync::atomic::{AtomicU64, Ordering};

static COUNTER: AtomicU64 = AtomicU64::new(0);

const ORPHAN_CHECK: &str = "lockfile/orphan-entries";

fn unique_dir() -> PathBuf {
    let id = COUNTER.fetch_add(1, Ordering::SeqCst);
    let dir = std::env::temp_dir().join(format!("sj-jsreach-{}-{}", std::process::id(), id));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// Parse a standalone yarn project (manifest + yarn.lock in the same dir).
fn yarn_project(manifest: &str, lock: &str) -> Result<LockfileData> {
    let dir = unique_dir();
    std::fs::write(dir.join("package.json"), manifest).unwrap();
    let lockfile = dir.join("yarn.lock");
    std::fs::write(&lockfile, lock).unwrap();
    let deps = crate::parsers::package_json::parse(&dir).unwrap();
    let result = LockfileData::parse_for_kind_with_lockfile(
        &dir,
        Some(LockfileKind::Ecosystem(Ecosystem::Npm)),
        &deps,
        Some(&lockfile),
    );
    let _ = std::fs::remove_dir_all(&dir);
    result
}

fn scanned(lock: &LockfileData) -> Vec<String> {
    lock.transitive_deps
        .iter()
        .map(|dep| dep.package_name().to_string())
        .collect()
}

fn orphan_issue(lock: &LockfileData) -> Option<&crate::report::Issue> {
    lock.resolution
        .issues
        .iter()
        .find(|issue| issue.check == ORPHAN_CHECK)
}

