#[test]
fn classic_real_transitives_including_optional_and_alias_children_are_scanned() {
    let lock = yarn_project(CLASSIC_MANIFEST, CLASSIC_LOCK).unwrap();
    let names = scanned(&lock);
    for expected in ["child-dep", "@scope/grand", "opt-dep", "alias-child"] {
        assert!(
            names.contains(&expected.to_string()),
            "{expected}: {names:?}"
        );
    }
    assert!(
        orphan_issue(&lock).is_none(),
        "{:?}",
        lock.resolution.issues
    );
}

#[test]
fn classic_orphan_entries_are_flagged_and_not_scanned() {
    let lock = yarn_project(
        CLASSIC_MANIFEST,
        &format!("{CLASSIC_LOCK}{CLASSIC_ORPHANS}"),
    )
    .unwrap();
    let names = scanned(&lock);
    assert!(!names.contains(&"ghost".to_string()), "{names:?}");
    assert!(!names.contains(&"ghost-child".to_string()), "{names:?}");
    // Real transitives are still scanned alongside the orphans.
    assert!(names.contains(&"child-dep".to_string()), "{names:?}");
    assert!(names.contains(&"opt-dep".to_string()), "{names:?}");
    let issue = orphan_issue(&lock).expect("orphan entries must be flagged");
    assert_eq!(issue.severity, Severity::Warning);
    assert!(issue.message.contains("ghost@9.0.0"), "{}", issue.message);
    assert!(
        issue.message.contains("ghost-child@1.0.0"),
        "{}",
        issue.message
    );
    assert!(issue.fix.contains("yarn install"), "{}", issue.fix);
}

