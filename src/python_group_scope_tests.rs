//! Python dependency groups and extras are installable by default (uv and Poetry install the
//! dev group without any flag, and `--all-extras` / `--with` are one flag away), so every
//! declared group and extra is scanned unless the operator narrows the selection explicitly.

use super::*;
use std::sync::atomic::{AtomicU64, Ordering};

static COUNTER: AtomicU64 = AtomicU64::new(0);

fn unique_dir() -> std::path::PathBuf {
    let id = COUNTER.fetch_add(1, Ordering::SeqCst);
    let dir = std::env::temp_dir().join(format!("sj-pygroups-{}-{}", std::process::id(), id));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

fn poetry_package(name: &str, version: &str, groups: &[&str], optional: bool) -> String {
    let file_stem = name.replace('-', "_");
    let groups = groups
        .iter()
        .map(|group| format!("\"{group}\""))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        r#"[[package]]
name = "{name}"
version = "{version}"
description = ""
optional = {optional}
python-versions = ">=3.8"
groups = [{groups}]
files = [
    {{file = "{file_stem}-{version}-py3-none-any.whl", hash = "sha256:1111111111111111111111111111111111111111111111111111111111111111"}},
]

"#
    )
}

fn write_poetry(dir: &std::path::Path, pyproject: &str, packages: &[String]) {
    std::fs::write(dir.join("pyproject.toml"), pyproject).unwrap();
    let hash = crate::lockfiles::python::poetry_content_hash_for_test(pyproject).unwrap();
    let mut lock = String::from(
        "# This file is automatically @generated by Poetry 2.1.3 and should not be changed by hand.\n\n",
    );
    for package in packages {
        lock.push_str(package);
    }
    lock.push_str(&format!(
        "[extras]\npretty = [\"rich\"]\n\n[metadata]\nlock-version = \"2.1\"\npython-versions = \"^3.12\"\ncontent-hash = \"{hash}\"\n"
    ));
    std::fs::write(dir.join("poetry.lock"), lock).unwrap();
}

const POETRY_GROUPS_PYPROJECT: &str = r#"[tool.poetry]
name = "demo"
version = "0.1.0"
package-mode = false

[tool.poetry.dependencies]
python = "^3.12"
requests = "2.31.0"
rich = { version = "13.7.1", optional = true }

[tool.poetry.extras]
pretty = ["rich"]

[tool.poetry.group.dev.dependencies]
pytest = "8.1.1"

[tool.poetry.group.docs]
optional = true

[tool.poetry.group.docs.dependencies]
mkdocs = "1.6.0"
"#;

fn poetry_groups_lock_packages() -> Vec<String> {
    vec![
        poetry_package("mkdocs", "1.6.0", &["docs"], false),
        poetry_package("pytest", "8.1.1", &["dev"], false),
        poetry_package("requests", "2.31.0", &["main"], false),
        poetry_package("rich", "13.7.1", &["main"], true),
    ]
}

fn opts_with(groups: &[&str], extras: &[&str]) -> ScanOptions<'static> {
    ScanOptions {
        python_groups: groups.iter().map(|value| value.to_string()).collect(),
        python_extras: extras.iter().map(|value| value.to_string()).collect(),
        ..Default::default()
    }
}

fn main_dep_names(
    dir: &std::path::Path,
    opts: &ScanOptions<'_>,
) -> (Vec<String>, Vec<Issue>, Vec<String>) {
    let config = config::SloppyJoeConfig::default();
    let specs = detected_project_inputs_with_config(dir, Some("pypi"), &config).unwrap();
    let warnings = preflight_project_inputs_with_options(dir, &specs, &config, opts)
        .expect("correctly locked project must pass preflight");
    let projects = parse_project_inputs_with_options(dir, &specs, &config, opts).unwrap();
    let main = projects
        .iter()
        .filter(|project| !project.unlocked_tooling)
        .flat_map(|project| project.deps.iter().map(|dep| dep.name.clone()))
        .collect();
    let tooling = projects
        .iter()
        .filter(|project| project.unlocked_tooling)
        .flat_map(|project| project.deps.iter().map(|dep| dep.name.clone()))
        .collect();
    (main, warnings, tooling)
}

#[test]
fn poetry_default_scan_includes_every_group_and_extra_and_trusts_a_correct_lock() {
    let dir = unique_dir();
    write_poetry(
        &dir,
        POETRY_GROUPS_PYPROJECT,
        &poetry_groups_lock_packages(),
    );

    let (names, warnings, _) = main_dep_names(&dir, &ScanOptions::default());
    for expected in ["requests", "rich", "pytest", "mkdocs"] {
        assert!(
            names.iter().any(|name| name == expected),
            "{expected} must be scanned by default: {names:?}"
        );
    }
    assert!(
        !warnings
            .iter()
            .any(|issue| issue.check == checks::names::RESOLUTION_PYTHON_GROUPS_NOT_SCANNED),
        "nothing was excluded, so no exclusion warning: {warnings:#?}"
    );

    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn poetry_group_dependency_missing_from_lock_is_a_blocking_error() {
    let dir = unique_dir();
    let mut packages = poetry_groups_lock_packages();
    packages.retain(|package| !package.contains("name = \"mkdocs\""));
    write_poetry(&dir, POETRY_GROUPS_PYPROJECT, &packages);

    let config = config::SloppyJoeConfig::default();
    let specs = detected_project_inputs_with_config(&dir, Some("pypi"), &config).unwrap();
    let err = preflight_project_inputs_with_options(&dir, &specs, &config, &ScanOptions::default())
        .expect_err("a declared group dependency absent from poetry.lock must block");
    let message = err.to_string();
    assert!(
        message.contains("mkdocs") && message.contains("missing"),
        "{message}"
    );

    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn python_groups_flag_narrows_groups_and_reports_unscanned_groups() {
    let dir = unique_dir();
    write_poetry(
        &dir,
        POETRY_GROUPS_PYPROJECT,
        &poetry_groups_lock_packages(),
    );

    let (names, warnings, _) = main_dep_names(&dir, &opts_with(&["dev"], &[]));
    assert!(names.iter().any(|name| name == "requests"), "{names:?}");
    assert!(names.iter().any(|name| name == "pytest"), "{names:?}");
    assert!(
        names.iter().any(|name| name == "rich"),
        "extras are not narrowed by --python-groups: {names:?}"
    );
    assert!(!names.iter().any(|name| name == "mkdocs"), "{names:?}");
    let excluded = warnings
        .iter()
        .find(|issue| issue.check == checks::names::RESOLUTION_PYTHON_GROUPS_NOT_SCANNED)
        .expect("narrowing must report the groups it hid");
    assert_eq!(excluded.severity, Severity::Warning);
    assert!(excluded.message.contains("docs"), "{}", excluded.message);

    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn python_extras_flag_narrows_extras_and_reports_unscanned_extras() {
    let dir = unique_dir();
    std::fs::write(
        dir.join("pyproject.toml"),
        r#"[project]
name = "demo"
version = "0.1.0"
dependencies = ["requests==2.31.0"]

[project.optional-dependencies]
docs = ["mkdocs==1.6.0"]
cli = ["click==8.1.7"]
"#,
    )
    .unwrap();

    let config = config::SloppyJoeConfig::default();
    let specs = detected_project_inputs_with_config(&dir, Some("pypi"), &config).unwrap();
    let default_projects =
        parse_project_inputs_with_options(&dir, &specs, &config, &ScanOptions::default()).unwrap();
    let default_names: Vec<_> = default_projects[0]
        .deps
        .iter()
        .map(|dep| dep.name.as_str())
        .collect();
    assert!(default_names.contains(&"mkdocs"), "{default_names:?}");
    assert!(default_names.contains(&"click"), "{default_names:?}");

    let opts = opts_with(&[], &["cli"]);
    let warnings = preflight_project_inputs_with_options(&dir, &specs, &config, &opts).unwrap();
    let projects = parse_project_inputs_with_options(&dir, &specs, &config, &opts).unwrap();
    let names: Vec<_> = projects[0]
        .deps
        .iter()
        .map(|dep| dep.name.as_str())
        .collect();
    assert!(names.contains(&"click"), "{names:?}");
    assert!(!names.contains(&"mkdocs"), "{names:?}");
    assert!(
        warnings.iter().any(|issue| {
            issue.check == checks::names::RESOLUTION_PYTHON_GROUPS_NOT_SCANNED
                && issue.message.contains("docs")
        }),
        "{warnings:#?}"
    );

    let _ = std::fs::remove_dir_all(&dir);
}

