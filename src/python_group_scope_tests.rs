#[test]
fn hatch_and_pdm_environments_in_a_poetry_project_are_unlocked_tooling() {
    let dir = unique_dir();
    let pyproject = format!(
        "{POETRY_GROUPS_PYPROJECT}\n[tool.hatch.envs.default]\ndependencies = [\"evil-hatch-env>=1\"]\n\n[tool.pdm.dev-dependencies]\nlint = [\"evil-pdm-dev>=1\"]\n"
    );
    write_poetry(&dir, &pyproject, &poetry_groups_lock_packages());

    // poetry.lock never records Hatch/PDM environments, so they must not be reported as lock
    // drift, but they are still installable and must be scanned.
    let (names, _, tooling) = main_dep_names(&dir, &ScanOptions::default());
    assert!(
        !names
            .iter()
            .any(|name| name == "evil-hatch-env" || name == "evil-pdm-dev"),
        "{names:?}"
    );
    assert!(
        tooling.iter().any(|name| name == "evil-hatch-env"),
        "{tooling:?}"
    );
    assert!(
        tooling.iter().any(|name| name == "evil-pdm-dev"),
        "{tooling:?}"
    );

    let _ = std::fs::remove_dir_all(&dir);
}
