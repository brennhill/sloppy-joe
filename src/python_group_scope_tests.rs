#[test]
fn include_group_entries_resolve_transitively_and_tag_the_including_group() {
    let dir = unique_dir();
    let path = write_pyproject(
        &dir,
        r#"[project]
name = "demo"
version = "0.1.0"

[dependency-groups]
test = ["pytest==8.1.1"]
typing = ["mypy==1.11.2", { include-group = "test" }]
dev = [{ include-group = "Typing" }, "ruff==0.6.9"]
"#,
    );
    let deps = parsers::pyproject_toml::parse_legacy_scoped_file(&path)
        .expect("include-group entries must be resolved, not rejected");
    let groups_of = |name: &str| -> std::collections::BTreeSet<String> {
        deps.iter()
            .filter(|dep| dep.dependency.name == name)
            .flat_map(|dep| dep.groups.iter().cloned())
            .collect()
    };
    assert_eq!(
        groups_of("pytest"),
        ["dev", "test", "typing"]
            .into_iter()
            .map(String::from)
            .collect()
    );
    assert_eq!(
        groups_of("mypy"),
        ["dev", "typing"].into_iter().map(String::from).collect()
    );
    assert_eq!(
        groups_of("ruff"),
        ["dev"].into_iter().map(String::from).collect()
    );

    let config = config::SloppyJoeConfig::default();
    let specs = detected_project_inputs_with_config(&dir, Some("pypi"), &config).unwrap();
    let projects =
        parse_project_inputs_with_options(&dir, &specs, &config, &opts_with(&["dev"], &[]))
            .unwrap();
    let names: Vec<_> = projects[0]
        .deps
        .iter()
        .map(|dep| dep.name.as_str())
        .collect();
    for expected in ["pytest", "mypy", "ruff"] {
        assert!(
            names.contains(&expected),
            "selecting dev must follow include-group: {names:?}"
        );
    }

    let _ = std::fs::remove_dir_all(&dir);
}

fn include_group_error(content: &str) -> String {
    let dir = unique_dir();
    let path = write_pyproject(&dir, content);
    let err = parsers::pyproject_toml::parse_legacy_scoped_file(&path)
        .expect_err("malformed include-group must fail closed");
    let _ = std::fs::remove_dir_all(&dir);
    err.to_string()
}

